export const blob = (rows: readonly string[], m: Ramp | string, seed = 1, extra: Pal = {}): Painter => (p) =>
  T(p, rows, { A: typeof m === "string" ? rampOf(m) : m, ...extra }, seed);

export function speckle(p: Px, hex: string, n: number, seed: number, onlyOpaque = true) {
  const r = rng(seed);
  for (let i = 0; i < n * 6 && n > 0; i++) {
    const x = (r() * 16) | 0, y = (r() * 16) | 0;
    const k = (y * 16 + x) * 4;
    if (onlyOpaque && !p[k + 3]) continue;
    const isEdge = !p[k + 3 - 4] || !p[k + 3 + 4] || !p[k + 3 - 64] || !p[k + 3 + 64];
    if (isEdge) continue;
    set(p, x, y, hex);
    n--;
  }
}

export const GLASS = "#c8dcec";
export const bottle = (rows: readonly string[], liquid: Ramp | null, glass = GLASS): Painter => (p) =>
  T(p, liquid ? rows : rows.map((r) => r.replace(/%/g, "e")), { B: liquid ?? undefined, g: glass, k: "#7a5a32", 0: "#4a3418", e: "#e8f2fa" }, 71);
