function redstoneSlab(p: Px, torches: [number, number][], mid: string) {
  T(p, [
    "................",
    "................",
    "................",
    "................",
    "................",
    "................",
    "................",
    "................",
    ".00000000000000.",
    ".0############0.",
    ".0############0.",
    ".00000000000000.",
    "................",
    "................",
    "................",
    "................",
  ], { A: rampOf("#9a9a9a", "#2e2e2e") }, 233);
  for (const [x] of torches) {
    for (let y = 5; y < 9; y++) set(p, x, y, y === 5 ? "#ff3a2a" : "#7a5a2a");
    set(p, x, 4, "#ff8a6a");
  }
  set(p, 7, 9, mid);
  set(p, 8, 9, mid);
}
