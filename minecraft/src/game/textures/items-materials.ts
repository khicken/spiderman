const ingot = (m: Ramp): Painter => (p) => T(p, INGOT, { A: m });
const raw = (m: Ramp, fleck: string): Painter => (p) => {
  T(p, RAW, { A: m }, 81);
  speckle(p, fleck, 6, 82);
};
const nugget = (m: Ramp): Painter => (p) => T(p, NUGGET, { A: m });
const pile = (m: Ramp | string, fleck?: string, seed = 83): Painter => (p) => {
  blob(PILE, m, seed)(p);
  if (fleck) speckle(p, fleck, 8, seed + 1);
};
const ball = (m: Ramp | string, seed = 84, hi = true): Painter => (p) => {
  blob(BALL, m, seed)(p);
  if (hi) {
    const r = typeof m === "string" ? rampOf(m) : m;
    set(p, 5, 5, r[4]);
    set(p, 6, 5, r[4]);
    set(p, 5, 6, r[4]);
  }
};

