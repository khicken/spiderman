export function stick(p: Uint8ClampedArray, x: number, y: number, n: number, pal = {}) {
  const rows: string[] = Array.from({ length: 16 }, () => "................");
  const put = (cx: number, cy: number, c: string) => {
    if (cx < 0 || cy < 0 || cx > 15 || cy > 15) return;
    const r = rows[cy];
    if (c === "a" && r[cx] !== ".") return;
    rows[cy] = r.slice(0, cx) + c + r.slice(cx + 1);
  };
  for (let i = 0; i < n; i++) {
    const cx = x + i, cy = y - i;
    put(cx, cy, i % 3 === 1 ? "d" : "c");
    put(cx - 1, cy, "a");
    put(cx + 1, cy, "a");
  }
  put(x - 1, y + 1, "a");
  T(p, rows, pal);
}

const tool = (shape: string, m: Ramp): Painter => (p) => {
  const pal = { A: m };
  if (shape === "sword") return T(p, SWORD, pal, 3);
  if (shape === "pickaxe") {
    stick(p, 1, 14, 10);
    T(p, PICKAXE.map((r) => r.replace(/[ac]/g, ".")), pal, 5);
    return T(p, PICKAXE_HANDLE_TOP, pal);
  }
  if (shape === "axe") {
    stick(p, 1, 14, 11);
    return T(p, AXE, pal, 7);
  }
  if (shape === "shovel") {
    stick(p, 1, 14, 9);
    return T(p, SHOVEL, pal, 9);
  }
  stick(p, 1, 14, 11);
  T(p, HOE, pal, 11);
};

export const TOOL_PAINTERS: Record<string, Painter> = {};
for (const m of Object.keys(MAT))
  for (const s of ["sword", "pickaxe", "axe", "shovel", "hoe"]) TOOL_PAINTERS[`${m}_${s}`] = tool(s, MAT[m]);
