const WINDOW_DOORS = new Set(["oak", "jungle", "acacia", "cherry", "mangrove", "warped", "crimson"]);
for (const [w, c] of Object.entries(WOOD)) {
  const pl = planks(c);
  const dark = rampOf(shade(c, 0.7), shade(c, 0.25));
  const boat = w === "bamboo" ? `${w}_raft` : `${w}_boat`;
  const chestBoat = w === "bamboo" ? `${w}_chest_raft` : `${w}_chest_boat`;
  if (w !== "crimson" && w !== "warped") {
    MISC_PAINTERS[boat] = (p) => T(p, w === "bamboo" ? RAFT : BOAT, { A: pl, B: dark }, 234);
    MISC_PAINTERS[chestBoat] = (p) => {
      MISC_PAINTERS[boat](p);
      chestOn(w === "bamboo" ? 5 : 4)(p);
    };
  }
  MISC_PAINTERS[`${w}_sign`] = (p) => T(p, SIGN, { A: pl, B: dark, t: shade(c, 0.55) }, 235);
  MISC_PAINTERS[`${w}_hanging_sign`] = (p) => T(p, HANGING, { A: pl, B: dark, t: shade(c, 0.55), c: "#4a5060" }, 236);
  MISC_PAINTERS[`${w}_door`] = (p) =>
    T(p, WINDOW_DOORS.has(w) ? DOOR : DOOR.map((r) => r.replace(/g/g, "#")), { A: pl, B: dark, g: mix(c, "#c8dcec", 0.6), k: "#3a3a3a" }, 237);
}
