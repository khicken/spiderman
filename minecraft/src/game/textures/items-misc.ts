const spawnEgg = (base: string, spot: string): Painter => (p) => {
  T(p, SPAWN_EGG, { A: rampOf(base, shade(base, 0.35)) }, 211);
  EGG_SPOTS.forEach((r, y) => {
    for (let x = 0; x < 16; x++) if (r[x] === "s" && p[(y * 16 + x) * 4 + 3]) set(p, x, y, spot);
  });
};

