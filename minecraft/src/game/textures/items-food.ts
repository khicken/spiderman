const FAT = "#f0d8d0";
const meat = (rows: readonly string[], m: Ramp, fat: string | null, seed: number): Painter => (p) => {
  T(p, rows, { A: m, w: "#ece6d6" }, seed);
  if (fat) {
    const r = rng(seed);
    for (let i = 0; i < 3; i++) {
      const y = 5 + i * 2 + ((r() * 2) | 0);
      for (let x = 3 + i; x < 7 + i * 2; x++) if (p[(y * 16 + x) * 4 + 3] && p[(y * 16 + x) * 4] > 60) set(p, x, y, fat);
    }
  }
};

const fish = (m: Ramp, fin: Ramp, seed: number, stripes?: string): Painter => (p) => {
  T(p, FISH, { A: m, B: fin, e: "#101010" }, seed);
  if (stripes) for (let y = 6; y < 10; y++) for (const x of [5, 9]) if (p[(y * 16 + x) * 4 + 3]) set(p, x, y, stripes);
};

const bowl = (contents: Ramp, extra?: (p: Px) => void): Painter => (p) => {
  T(p, BOWL, { A: rampOf("#8a6438", "#2e1e0c"), B: contents }, 151);
  if (extra) extra(p);
};

const apple = (m: Ramp): Painter => (p) => T(p, APPLE, { A: m, s: "#5a3a1a", l: "#4a9a2a" }, 152);
const carrot = (m: Ramp): Painter => (p) => T(p, CARROT, { A: m, l: "#3c8a2a" }, 153);
const potato = (m: Ramp, fleck: string, seed: number): Painter => (p) => {
  T(p, LUMP, { A: m }, seed);
  speckle(p, fleck, 5, seed + 1);
};

