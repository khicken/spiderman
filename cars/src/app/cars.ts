// Box approximation scaled down because the mass sits low and central. Returns pitch, yaw, roll.
function inertia(m: number, l: number, w: number, h: number): [number, number, number] {
  return [(m * (l * l + h * h)) / 12 * 0.85, (m * (l * l + w * w)) / 12 * 0.9, (m * (w * w + h * h)) / 12 * 0.8];
}

// Constant power above the base speed of the motor.
function motorCurve(torque: number, kw: number, max: number): [number, number][] {
  const base = (kw * 1000) / torque / (Math.PI / 30);
  const out: [number, number][] = [[0, torque], [Math.round(base), torque]];
  for (let r = Math.ceil(base / 2000) * 2000; r <= max; r += 2000) if (r > base) out.push([r, Math.round((kw * 1000) / (r * (Math.PI / 30)))]);
  return out;
}

